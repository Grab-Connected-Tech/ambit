// llmBudget is §17.5's ceiling, in the usual four-bytes-per-token estimate.
const llmBudget = 40000 * 4

const llmIntro = `KEYSTONE FRAMEWORK REFERENCE (for models)
Generated by ks docs --llm from the installed framework's source; prefer it over memory.

THE LOOP
1. ks context <module> - read the module's spec and generated signatures.
2. Edit app/<module>/spec.go - resources, rules, actions. Spec files hold declarations only.
3. ks gen - regenerates gen/, the client, migrations/schema.gen.sql, AGENTS.md; stubs new actions.
4. Implement actions in app/<module>/actions.go (an Actions struct of functions).
5. ks check --json until no errors. 6. ks test --json until green. 7. ks diff --base main.

RULES OF THE ROAD
- Actions reach data only through c.DB (scoped: tenant + Read rule are always applied),
  effects only through the context's declared handles, time only through c.Clock.
- Return declared failures with gen.Err<Action><Code>(); anything else is an internal error.
- Queries end in Get, First, Page or a job's Each; Count needs Counts(). No raw SQL outside ks.Unsafe.
- Optional values are ks.Opt[T]; money is ks.Money (minor units); ids are ks.ID.
- Tests: env := kstest.New(t, gen.Model); kstest.Call(env, actor, gen.XHandler, Actions.X, input).
`

// cmdDocs writes the single-file framework reference for models (§17.5).
func cmdDocs(args []string) error {
	var out *string
	var llm *bool
	_, _, err := flags("docs", args, func(fs *flag.FlagSet) {
		llm = fs.Bool("llm", false, "write the single-file reference for models")
		out = fs.String("out", "", "file to write (default stdout)")
	})
	if err != nil {
		return err
	}
	if !*llm {
		return fmt.Errorf("usage: ks docs --llm [--out file]")
	}
	root, err := frameworkDir()
	if err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString(llmIntro)
	for _, p := range []struct{ dir, title string }{
		{"spec", "SPEC DSL (package spec, imported as s)"},
		{"ks", "SCALARS, ERRORS AND ACTORS (package ks)"},
		{"kstest", "TESTING (package kstest)"},
	} {
		if err := packageDoc(&b, filepath.Join(root, p.dir), p.title, nil); err != nil {
			return err
		}
	}
	// The runtime is large; actions only meet its data-layer surface.
	if err := packageDoc(&b, filepath.Join(root, "runtime"), "DATA LAYER (package runtime, as used by actions)",
		map[string]bool{"View": true, "Query": true, "Col": true, "TextCol": true, "IDCol": true, "OptCol": true,
			"MoneyCol": true, "PageOf": true, "With": true, "EffectHandle": true, "EffectResult": true, "Assignment": true,
			"SetColumn": true, "SetOpt": true, "SetExpr": true}); err != nil {
		return err
	}
	b.WriteString("\nCHECKER RULES (ks explain <ID> for examples)\n")
	b.WriteString(checker.RuleIndex())
	b.WriteString("\nCLI\n" + usage)
	if b.Len() > llmBudget {
		return fmt.Errorf("the reference is %d bytes, over the %d-byte budget of §17.5", b.Len(), llmBudget)
	}
	fmt.Fprintf(os.Stderr, "ks docs: about %d tokens\n", b.Len()/4)
	if *out == "" {
		_, err = os.Stdout.Write(b.Bytes())
		return err
	}
	return os.WriteFile(*out, b.Bytes(), 0o644)
}

// frameworkDir is the source of the Keystone the app builds against.
func frameworkDir() (string, error) {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "keystone.dev/keystone").Output()
	if err != nil || strings.TrimSpace(string(out)) == "" {
		return "", fmt.Errorf("cannot find the keystone.dev/keystone source (run inside an app module): %v", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// packageDoc writes a package's exported API: declarations with the first paragraph of
// their documentation. keep, when set, limits the output to those names.
func packageDoc(b *bytes.Buffer, dir, title string, keep map[string]bool) error {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	var files []*ast.File
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, e.Name()), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		files = append(files, f)
	}
	pkg, err := doc.NewFromFiles(fset, files, "keystone.dev/keystone/"+filepath.Base(dir))
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "\n%s\n", title)
	if keep == nil {
		b.WriteString(indentDoc(firstPara(pkg.Doc)))
	}
	decl := func(n ast.Node) string {
		var s bytes.Buffer
		if fn, ok := n.(*ast.FuncDecl); ok {
			fn.Body, fn.Doc = nil, nil
		}
		if gd, ok := n.(*ast.GenDecl); ok {
			gd.Doc = nil
		}
		_ = printer.Fprint(&s, fset, n)
		return s.String()
	}
	want := func(name string) bool { return keep == nil || keep[name] }
	for _, f := range pkg.Funcs {
		if want(f.Name) {
			fmt.Fprintf(b, "%s\n%s", decl(f.Decl), indentDoc(firstPara(f.Doc)))
		}
	}
	for _, t := range pkg.Types {
		if !want(t.Name) {
			continue
		}
		fmt.Fprintf(b, "%s\n%s", decl(t.Decl), indentDoc(firstPara(t.Doc)))
		for _, f := range t.Funcs {
			fmt.Fprintf(b, "%s\n%s", decl(f.Decl), indentDoc(firstPara(f.Doc)))
		}
		for _, m := range t.Methods {
			fmt.Fprintf(b, "%s\n%s", decl(m.Decl), indentDoc(firstPara(m.Doc)))
		}
	}
	return nil
}

func firstPara(s string) string {
	p, _, _ := strings.Cut(strings.TrimSpace(s), "\n\n")
	return strings.Join(strings.Fields(p), " ")
}

func indentDoc(s string) string {
	if s == "" {
		return ""
	}
	return "    " + s + "\n"
}
