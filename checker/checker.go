// stmtDiscardsResult reports whether a call's results vanish: the expression is a
// statement by itself.
func stmtDiscardsResult(f *ast.File, call ast.Node) bool {
	found := false
	ast.Inspect(f, func(n ast.Node) bool {
		if es, ok := n.(*ast.ExprStmt); ok && es.X == call {
			found = true
			return false
		}
		return true
	})
	return found
}

func allowedThirdParty(p string, list []string) bool {
	for _, a := range list {
		if p == a || strings.HasPrefix(p, strings.TrimSuffix(a, "/")+"/") {
			return true
		}
	}
	return false
}

// moduleOf maps a path to the module that owns it: the folder holding actions/ or
// gen/, or the file's own folder when it is a spec.
// isGenerated reports a file carrying Go's standard generated-code header.
func isGenerated(f *ast.File) bool {
	for _, c := range f.Comments {
		if c.Pos() > f.Package {
			break
		}
		if strings.HasPrefix(c.Text(), "Code generated") && strings.Contains(c.Text(), "DO NOT EDIT") {
			return true
		}
	}
	return false
}

func moduleOf(path string) string {
	parts := strings.Split(filepath.ToSlash(path), "/")
	for i, p := range parts {
		if (p == "actions" || p == "gen") && i > 0 {
			return parts[i-1]
		}
	}
	if len(parts) > 1 {
		return parts[len(parts)-2]
	}
	return "app"
}

func rel(root, path string) string {
	r := strings.TrimPrefix(filepath.ToSlash(path), filepath.ToSlash(root)+"/")
	if r == "" {
		return filepath.Base(path)
	}
	return r
}

func sortDiags(d []compile.Diag) {
	sort.SliceStable(d, func(i, j int) bool {
		if d[i].File != d[j].File {
			return d[i].File < d[j].File
		}
		if d[i].Line != d[j].Line {
			return d[i].Line < d[j].Line
		}
		return d[i].Rule < d[j].Rule
	})
}

func dedupeStrings(in []string) []string {
	sort.Strings(in)
	var out []string
	for _, x := range in {
		if len(out) > 0 && out[len(out)-1] == x {
			continue
		}
		out = append(out, x)
	}
	return out
}
