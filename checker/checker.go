// Package checker runs Ambit's analyzers over an app's source and extracts the
// code facts the behavior diff reports (§14, §6.3). With Config.Types set, the rules
// resolve names through go/types (what a call is, not how it is spelled); without it,
// or for test files, they fall back to syntax plus the app model.
package checker

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/Grab-Connected-Tech/ambit/compile"
	"github.com/Grab-Connected-Tech/ambit/model"
)

// Config selects what to analyze.
type Config struct {
	Root           string   // app directory
	ModulePath     string   // go import path of the app root
	GoMod          string   // contents of go.mod, for dependency facts
	AllowedImports []string // am.yaml allowedImports (§7.4)
	App            *model.App
	Strict         bool
	// Types runs the type-aware rules. It needs a module that builds; when the type
	// check fails anyway, the run reports AM-CODE-006 rather than silently degrading.
	Types bool
}

// Result is the checker's whole answer.
type Result struct {
	Diags []compile.Diag
	Facts model.Facts
}

// banned reaches the outside world directly (§7.4).
var banned = map[string]string{
	"database/sql":         "use the action's scoped DB",
	"runtime":              "the runtime owns process state",
	"sync/atomic":          "use a declared resource and an optimistic version",
	"net":                  "use the HTTP effect",
	"net/http":             "use the HTTP effect",
	"net/url":              "use am.URL",
	"os":                   "read configuration through the generated config",
	"os/exec":              "there is no subprocess in a request",
	"syscall":              "the runtime owns process state",
	"reflect":              "generated code needs no reflection",
	"unsafe":               "there is no unchecked memory in an app",
	"plugin":               "there is no dynamic loading",
	"context":              "the action context is already a context.Context",
	"io":                   "streams do not cross an action boundary; use Bytes or the Storage effect",
	"log":                  "use c.Log",
	"github.com/jackc/pgx": "use the action's scoped DB",
}

// stdAllowed is the pure standard-library allowlist from §7.4.
var stdAllowed = map[string]bool{
	"strings": true, "strconv": true, "errors": true, "fmt": true, "slices": true,
	"maps": true, "sort": true, "math": true, "unicode": true, "unicode/utf8": true,
	"regexp": true, "time": true, "encoding/json": true, "math/bits": true,
	"github.com/Grab-Connected-Tech/ambit/am": true,
}

var allowRe = regexp.MustCompile(`//\s*am:allow\s+(AM-[A-Z]+-\d+)\s*(.*)$`)
var generatedMark = "// Code generated by am. DO NOT EDIT."

// Run analyzes every Go file under cfg.Root.
func Run(cfg Config) (Result, error) {
	var res Result
	if cfg.App == nil {
		cfg.App = &model.App{}
	}
	var files []string
	err := filepath.Walk(cfg.Root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() {
			name := info.Name()
			if name == "client" || name == "migrations" || name == "seed" || name == ".git" || name == "node_modules" {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(path, ".go") {
			files = append(files, path)
		}
		return nil
	})
	if err != nil {
		return res, err
	}
	sort.Strings(files)
	fset := token.NewFileSet()
	parsed := map[string]*ast.File{}
	for _, path := range files {
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			res.Diags = append(res.Diags, compile.Diag{
				Rule: "AM-CODE-001", Severity: compile.SevError, File: rel(cfg.Root, path),
				Message: "the file does not parse: " + err.Error(),
				Fix:     "fix the syntax", Docs: "am explain AM-CODE-001",
			})
			continue
		}
		abs, _ := filepath.Abs(path)
		parsed[abs] = f
	}
	var info *types.Info
	var typed map[*ast.File]bool
	if cfg.Types {
		var err error
		if info, typed, err = typeCheck(cfg.Root, fset, parsed); err != nil {
			res.Diags = append(res.Diags, compile.Diag{
				Rule: "AM-CODE-006", Severity: compile.SevError,
				Message: "type-aware checks could not run, so these files were checked by syntax only: " + err.Error(),
				Fix:     "make sure go build ./... passes with the same Go toolchain am was built with",
				Docs:    "am explain AM-CODE-006",
			})
		}
	}
	for _, path := range files {
		abs, _ := filepath.Abs(path)
		f := parsed[abs]
		if f == nil {
			continue
		}
		v := &visitor{cfg: cfg, fset: fset, file: f, path: rel(cfg.Root, path), abs: path, res: &res}
		if typed[f] {
			v.info = info
		}
		v.classify()
		v.run()
	}
	checkImplementations(cfg, &res)
	checkGeneratedHashes(cfg, &res)
	checkTests(cfg, &res)
	checkSuppressions(&res)
	sortDiags(res.Diags)
	res.Facts.App = cfg.App.Name()
	res.Facts.ModelHash = cfg.App.Hash()
	res.Facts.Imports = dedupeStrings(res.Facts.Imports)
	res.Facts.Deps = parseDeps(cfg.GoMod)
	res.Facts.Generated = "v0.1"
	return res, nil
}

// visitor holds one file's analysis state.
type visitor struct {
	cfg        Config
	fset       *token.FileSet
	file       *ast.File
	path       string // app-relative, for diagnostics
	abs        string // on disk, for reading
	inActions  bool
	innerCalls map[ast.Node]bool
	res        *Result
	module     string
	action     string // the action this file implements, when it is an action file
	kind       fileKind
	lines      []string
	info       *types.Info // nil when the file is checked by syntax only
}

type fileKind int

const (
	fileOther fileKind = iota
	fileSpec
	fileAction
	fileGenerated
	fileTest
)

func (v *visitor) classify() {
	base := filepath.Base(v.path)
	v.module = moduleOf(v.path)
	switch {
	case strings.HasSuffix(base, "_test.go"):
		// A test in an actions folder still runs the action rules, because the code
		// under test is action code; only its imports are more permissive.
		v.kind = fileTest
		v.inActions = strings.Contains(v.path, "/actions/")
		v.action = strings.TrimSuffix(base, "_test.go")
	case strings.HasSuffix(base, ".gen.go") || strings.Contains(v.path, "/gen/") || isGenerated(v.file):
		// The generated entrypoint (cmd/server/main.go) lives outside gen/.
		v.kind = fileGenerated
	case strings.Contains(v.path, "/actions/"):
		v.kind = fileAction
		v.action = strings.TrimSuffix(base, ".go")
	case strings.HasSuffix(base, "spec.go") || strings.HasSuffix(base, "app.go"):
		v.kind = fileSpec
	case len(strings.Split(v.path, "/")) == 3 && strings.HasPrefix(v.path, "app/"):
		// A module that keeps its actions beside its spec (app/<module>/actions.go).
		v.kind = fileAction
		v.module = strings.Split(v.path, "/")[1]
	}
	if data, err := os.ReadFile(v.abs); err == nil {
		v.lines = strings.Split(string(data), "\n")
	}
}

func (v *visitor) pos(n ast.Node) (string, int) {
	p := v.fset.Position(n.Pos())
	return rel(v.cfg.Root, p.Filename), p.Line
}

func (v *visitor) at(rule string, n ast.Node, msg, fix string) {
	file, line := v.pos(n)
	severity := compile.SevError
	if r, ok := RuleByID(rule); ok && r.Severity == "warning" {
		severity = compile.SevWarning
	}
	v.res.Diags = append(v.res.Diags, compile.Diag{
		Rule: rule, Severity: severity, File: file, Line: line, Decl: v.module,
		Message: msg, Fix: fix, Docs: "am explain " + rule,
	})
}

func (v *visitor) run() {
	switch v.kind {
	case fileSpec:
		v.checkSpecFile()
	case fileGenerated:
		v.checkGeneratedFile()
	case fileAction:
		v.checkActionFile()
	case fileTest:
		v.checkImports()
		if v.inActions {
			v.checkActionFile()
		}
	default:
		v.checkImports()
	}
	_ = fileOther
	v.collectFacts()
}

// checkSpecFile enforces the restricted language of §5.1: only declarations built
// from the spec package, no functions, no control flow.
func (v *visitor) checkSpecFile() {
	for _, d := range v.file.Decls {
		switch x := d.(type) {
		case *ast.FuncDecl:
			v.at("AM-SPEC-001", x, "spec files may not contain functions",
				"move behavior into an action; a spec declares what exists, not what happens")
		case *ast.GenDecl:
			for _, s := range x.Specs {
				if _, isImport := s.(*ast.ImportSpec); isImport {
					continue // imports are checked by checkSpecFile's import loop
				}
				vd, ok := s.(*ast.ValueSpec)
				if !ok {
					v.at("AM-SPEC-001", s, "spec files may only declare values", "use a var declaration with spec builders")
					continue
				}
				if len(vd.Values) == 0 {
					continue
				}
				for _, val := range vd.Values {
					v.walkExpr(val, 0)
				}
			}
		default:
			v.at("AM-SPEC-001", d, "unsupported declaration in a spec file", "use var with spec builders")
		}
	}
	for _, imp := range v.file.Imports {
		p := strings.Trim(imp.Path.Value, `"`)
		if strings.HasSuffix(p, "/spec") || p == "github.com/Grab-Connected-Tech/ambit/spec" {
			continue
		}
		if strings.Contains(p, "/actions") || strings.Contains(p, "/gen") {
			v.at("AM-SPEC-001", imp, "a spec file may not import generated or action code",
				"import the module's spec package instead")
		}
	}
}

// walkExpr rejects anything inside a spec value that is not a builder call, a
// literal, an identifier or a selector.
func (v *visitor) walkExpr(e ast.Expr, depth int) {
	if depth > 24 {
		return
	}
	switch x := e.(type) {
	case *ast.CallExpr:
		for _, a := range x.Args {
			v.walkExpr(a, depth+1)
		}
		switch x.Fun.(type) {
		case *ast.SelectorExpr, *ast.Ident:
			// a builder call or a conversion; conversions of non-literals are rare enough
			// to allow here and are still reviewed as text
		default:
			v.at("AM-SPEC-001", x, "spec values may only be built from spec functions", "call a builder from the spec package")
		}
	case *ast.CompositeLit:
		for _, elt := range x.Elts {
			if kv, ok := elt.(*ast.KeyValueExpr); ok {
				v.walkExpr(kv.Value, depth+1)
				continue
			}
			v.walkExpr(elt, depth+1)
		}
	case *ast.BinaryExpr:
		// 30 * s.Day is arithmetic on literals, which the spec language allows
		v.walkExpr(x.X, depth+1)
		v.walkExpr(x.Y, depth+1)
	case *ast.Ident, *ast.SelectorExpr, *ast.BasicLit, *ast.ParenExpr:
	case *ast.UnaryExpr:
		v.walkExpr(x.X, depth+1)
	case *ast.FuncLit:
		v.at("AM-SPEC-001", x, "spec values may not contain function literals",
			"declare behavior in an action instead")
	default:
		v.at("AM-SPEC-001", x, "spec values must be literals or builder calls", "keep the spec declarative")
	}
}

func (v *visitor) checkGeneratedFile() {
	src := strings.Join(v.lines, "\n")
	if !strings.Contains(src, generatedMark) {
		v.res.Diags = append(v.res.Diags, compile.Diag{
			Rule: "AM-CODE-001", Severity: compile.SevError, File: v.path, Line: 1,
			Message: "a file under gen/ is missing the generated marker, so it was hand-edited",
			Fix:     "run am gen", Docs: "am explain AM-CODE-001",
		})
		return
	}
	if want := hashMarker(src); want != "" && !hashMatches(src, want) {
		v.res.Diags = append(v.res.Diags, compile.Diag{
			Rule: "AM-CODE-001", Severity: compile.SevError, File: v.path, Line: 1,
			Message: "generated file was edited after am gen (content hash differs)",
			Fix:     "run am gen, or move the change into the spec and regenerate",
			Docs:    "am explain AM-CODE-001",
		})
	}
}

// checkActionFile applies the rules that keep action code inside its box.
func (v *visitor) checkActionFile() {
	if v.kind != fileTest {
		v.checkImports()
	}
	v.checkActionFuncs()

	v.markInner()
	v.walkCalls()
}

// walkCalls visits every call with the number of enclosing loops, which is what
// makes the N+1 rule (AM-DATA-002) a syntactic check instead of a guess.
func (v *visitor) walkCalls() {
	var stack []ast.Node
	loops := 0
	ast.Inspect(v.file, func(n ast.Node) bool {
		if n == nil {
			if len(stack) > 0 {
				switch stack[len(stack)-1].(type) {
				case *ast.ForStmt, *ast.RangeStmt:
					loops--
				}
				stack = stack[:len(stack)-1]
			}
			return false
		}
		stack = append(stack, n)
		switch x := n.(type) {
		case *ast.FuncDecl:
			// Facts belong to the function they sit in, not the file's last one.
			if x.Recv == nil && v.kind != fileTest {
				v.action = strings.ToUpper(x.Name.Name[:1]) + x.Name.Name[1:]
			}
		case *ast.ForStmt, *ast.RangeStmt:
			loops++
		case *ast.GoStmt:
			v.at("AM-PERF-003", x, "a goroutine outlives the transaction",
				"declare a job and call the Enqueue effect instead")
		case *ast.CallExpr:
			v.checkCall(x, loops)
		case *ast.SelectorExpr:
			v.checkTimeUse(x)
			v.checkFuncRef(x, x.Sel, stack)
		case *ast.Ident:
			v.checkFuncRef(x, x, stack)
		}
		return true
	})
}

// checkFuncRef judges a typed reference to time.Now and friends, and to am.Unsafe
// used as a value: a block run through a func variable would never be recorded.
func (v *visitor) checkFuncRef(n ast.Expr, id *ast.Ident, stack []ast.Node) {
	if v.info == nil || len(stack) < 2 {
		return
	}
	parent := stack[len(stack)-2]
	if sel, ok := parent.(*ast.SelectorExpr); ok && sel.Sel == n {
		return // judged at the selector
	}
	fn, _ := v.info.Uses[id].(*types.Func)
	if fn == nil {
		return
	}
	if _, isSel := n.(*ast.SelectorExpr); !isSel && isFunc(fn, "time", "Now", "Since", "Until") {
		v.at("AM-CODE-004", n, "wall-clock time is not available to actions",
			"use c.Clock.Now() and c.Clock.Since() so tests control time")
	}
	// A call rule only sees direct calls, so a function that one of them judges may
	// not be taken as a value: fetch := view.Get; fetch(...) would hide the call.
	callee := n
	if len(stack) >= 3 {
		switch parent.(type) {
		case *ast.IndexExpr, *ast.IndexListExpr: // f[T](...)
			callee, parent = parent.(ast.Expr), stack[len(stack)-3]
		}
	}
	if call, ok := parent.(*ast.CallExpr); ok && ast.Unparen(call.Fun) == callee {
		return
	}
	const direct = "call it directly so the checker can see the call"
	switch {
	case isFunc(fn, amPkg, "Unsafe"):
		v.at("AM-SEC-003", n, "am.Unsafe is used as a value, so its block cannot be recorded",
			`call it directly: am.Unsafe(c, "reason", func(tx am.RawTx) error { ... })`)
	case isDBCallTyped(fn):
		v.at("AM-DATA-002", n, fn.Name()+" runs a query and is used as a value, which hides it from the data rules", direct)
	case isEffectCallTyped(fn):
		v.at("AM-DATA-003", n, fn.Name()+" runs an effect and is used as a value, which hides its error from the checker", direct)
	case isLoggerTyped(fn):
		v.at("AM-SEC-004", n, fn.Name()+" logs or builds an error and is used as a value, which hides Sensitive fields passed to it", direct)
	}
}

// markInner records every call that is the left-hand side of a longer chain, so a
// chain like Query().Where().Page() is judged once, on its outermost node.
func (v *visitor) markInner() {
	v.innerCalls = map[ast.Node]bool{}
	ast.Inspect(v.file, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		switch fn := call.Fun.(type) {
		case *ast.CallExpr:
			v.innerCalls[fn] = true
		case *ast.SelectorExpr:
			if inner, ok := fn.X.(*ast.CallExpr); ok {
				v.innerCalls[inner] = true
			}
		}
		return true
	})
}

func (v *visitor) inner(n ast.Node) bool { return v.innerCalls[n] }

func (v *visitor) checkCall(x *ast.CallExpr, loopDepth int) {
	text := exprText(v.fset, v.file, x)
	if v.info != nil {
		v.checkCallTyped(x, text, loopDepth)
		return
	}

	if strings.HasPrefix(text, "am.Unsafe(") || strings.Contains(text, "am.Unsafe(") {
		v.checkUnsafe(x)
	}

	if isDBCall(text) {
		v.checkDBCall(x, text, loopDepth)
	}
	if isEffectCall(text) && stmtDiscardsResult(v.file, x) && !strings.Contains(text, ".Send(") {
		v.at("AM-DATA-003", x, "the error from an effect call is ignored", "check the error or return it")
	}
	if strings.Contains(text, ".Query()") && !hasTerminalBound(text) && !v.inner(x) {
		v.at("AM-DATA-001", x, "the query has no terminal bound",
			"end the chain with Page, First, Get, Count or Each (AM-DATA-001)")
	}
	if strings.Contains(text, "os.Getenv") || strings.Contains(text, "os.LookupEnv") {
		v.at("AM-SEC-002", x, "an action reads an environment variable",
			"declare the secret in am.yaml and receive it through the generated config")
	}
	for _, a := range x.Args {
		if sel, ok := a.(*ast.SelectorExpr); ok {
			if f := v.sensitiveField(sel); f != "" {
				if isLogger(text) {
					v.at("AM-SEC-004", x, fmt.Sprintf("%s is a Sensitive field and is passed to a log or error message", f),
						"log the resource id instead: c.Log.Info(\"paid\", \"invoice_id\", inv.ID)")
				}
			}
		}
	}
}

// checkCallTyped is checkCall with every "what is this call" answered by go/types.
// AM-DATA-001 has no typed form: runtime.Query offers only bounded terminals, so an
// unbounded read does not type-check in the first place.
func (v *visitor) checkCallTyped(x *ast.CallExpr, text string, loopDepth int) {
	fn := v.callee(x)
	if fn == nil {
		return
	}
	switch {
	case isFunc(fn, amPkg, "Unsafe"):
		v.checkUnsafe(x)
	case isDBCallTyped(fn):
		v.checkDBCall(x, text, loopDepth)
	case isEffectCallTyped(fn):
		if stmtDiscardsResult(v.file, x) {
			v.at("AM-DATA-003", x, "the error from an effect call is ignored", "check the error or return it")
		}
	case isFunc(fn, "os", "Getenv", "LookupEnv", "Environ"):
		v.at("AM-SEC-002", x, "an action reads an environment variable",
			"declare the secret in am.yaml and receive it through the generated config")
	case isLoggerTyped(fn):
		// Any Sensitive field read anywhere in the arguments, not only a bare one.
		for _, a := range x.Args {
			ast.Inspect(a, func(n ast.Node) bool {
				if sel, ok := n.(*ast.SelectorExpr); ok {
					if f := v.sensitiveFieldTyped(sel); f != "" {
						v.at("AM-SEC-004", x, fmt.Sprintf("%s is a Sensitive field and is passed to a log or error message", f),
							"log the resource id instead: c.Log.Info(\"paid\", \"invoice_id\", inv.ID)")
					}
				}
				return true
			})
		}
	}
}

// checkDBCall applies the data rules to a call that runs SQL.
func (v *visitor) checkDBCall(x *ast.CallExpr, text string, loopDepth int) {
	if loopDepth > 0 {
		v.at("AM-DATA-002", x, "a scoped DB call inside a loop issues one query per iteration",
			"load the relation with .With(gen.XWithY) on the outer query, then read it in the loop")
	}
	if stmtDiscardsResult(v.file, x) {
		v.at("AM-DATA-003", x, "the error from a data call is ignored",
			"handle err: return nil, err")
	}
	v.res.Facts.Queries = append(v.res.Facts.Queries, model.QueryFact{Action: v.module + "." + v.action, SQL: text, Count: 1})
}

// checkUnsafe requires a constant reason and records the block as a code fact.
func (v *visitor) checkUnsafe(x *ast.CallExpr) {
	reason := ""
	if len(x.Args) >= 2 {
		if lit, ok := x.Args[1].(*ast.BasicLit); ok && lit.Kind == token.STRING {
			reason = strings.Trim(lit.Value, `"`)
		} else {
			v.at("AM-SEC-003", x, "the unsafe reason must be a constant string",
				"write the reason inline so a reviewer sees it in the file")
			return
		}
	}
	if strings.TrimSpace(reason) == "" {
		v.at("AM-SEC-003", x, "am.Unsafe has no reason",
			`state why the guarantee must be weakened: am.Unsafe(c, "reason", ...)`)
		return
	}
	v.res.Facts.Unsafe = append(v.res.Facts.Unsafe, model.UnsafeFact{
		File: v.path, Line: v.fset.Position(x.Pos()).Line, Module: v.module, Action: v.actionName(x),
		Kind: "raw_sql", Reason: reason,
	})
}

func (v *visitor) checkTimeUse(x *ast.SelectorExpr) {
	if v.info != nil {
		if fn, _ := v.info.Uses[x.Sel].(*types.Func); isFunc(fn, "time", "Now", "Since", "Until") {
			v.at("AM-CODE-004", x, "wall-clock time is not available to actions",
				"use c.Clock.Now() and c.Clock.Since() so tests control time")
		}
		return
	}
	text := exprText(v.fset, v.file, x)
	switch text {
	case "time.Now", "time.Since", "time.Until", "time.Now()":
		v.at("AM-CODE-004", x, "wall-clock time is not available to actions",
			"use c.Clock.Now() and c.Clock.Since() so tests control time")
	}
}

func (v *visitor) checkImports() {
	for _, imp := range v.file.Imports {
		p := strings.Trim(imp.Path.Value, `"`)
		if !strings.Contains(p, ".") || strings.HasPrefix(p, "github.com/Grab-Connected-Tech/ambit/") {
			if !strings.Contains(p, ".") {
				v.res.Facts.Imports = append(v.res.Facts.Imports, p)
			}
		} else if v.cfg.ModulePath == "" || !strings.HasPrefix(p, v.cfg.ModulePath) {
			// Every non-stdlib import is recorded: the dependency rows of the behavior
			// diff come from here, not from a separate scan.
			v.res.Facts.Imports = append(v.res.Facts.Imports, p)
		}
		if v.kind == fileTest {
			switch {
			case p == "testing", p == "context", strings.HasSuffix(p, "/amtest"), strings.HasSuffix(p, "/go/assert"),
				strings.HasSuffix(p, "/stretchr/testify"):
				continue
			case p == v.cfg.ModulePath+"/app/"+v.module+"/actions":
				continue // a test imports the actions it drives
			}
		}
		ownPrefix := v.cfg.ModulePath + "/app/" + v.module
		switch {
		case v.kind == fileSpec && strings.HasPrefix(p, ownPrefix):
			continue
		case banned[p] != "":
			v.at("AM-SEC-001", imp, "an action may not import "+p, banned[p])
		case strings.Contains(p, "/actions"):
			v.at("AM-CODE-002", imp, "importing another module's actions package skips its rules",
				"declare the call with s.Calls and invoke it through the context")
		case stdAllowed[p]:
		case p == "github.com/Grab-Connected-Tech/ambit/spec":
			if v.kind == fileAction {
				v.at("AM-CODE-001", imp, "action code may not import the spec package",
					"actions use generated types; the spec is the declaration of what exists")
			}
		case strings.HasPrefix(p, "github.com/Grab-Connected-Tech/ambit"):
		case strings.HasPrefix(p, v.cfg.ModulePath):
			if v.kind == fileAction && !strings.HasSuffix(p, "/gen") && !strings.HasSuffix(p, "/"+v.module) && !strings.HasSuffix(p, "/app") {
				v.at("AM-CODE-002", imp, "actions may only import another module's gen package",
					"import "+p+"/gen, or declare the call in the spec")
			}
		case strings.Contains(p, "."):
			if v.kind == fileSpec {
				continue // a spec may import the packages it references by value
			}
			if !allowedThirdParty(p, v.cfg.AllowedImports) {
				v.at("AM-SEC-001", imp, "third-party import "+p+" is not in allowedImports",
					"list it under allowedImports in am.yaml after reviewing it, or use a declared effect")
			}
			v.res.Facts.Imports = append(v.res.Facts.Imports, p)
		default:
			v.at("AM-SEC-001", imp, "unrecognized import "+p, "use the framework packages")
		}
	}
}

// checkActionFuncs verifies the file looks like an action implementation and records
// enum switches that are not exhaustive.
func (v *visitor) checkActionFuncs() {
	ast.Inspect(v.file, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.FuncDecl:
			if x.Recv != nil {
				return true
			}
			// sendInvoice in a module package implements SendInvoice.
			v.action = strings.ToUpper(x.Name.Name[:1]) + x.Name.Name[1:]
		case *ast.SwitchStmt:
			v.checkEnumSwitch(x)
		}
		return true
	})
}

func (v *visitor) checkEnumSwitch(x *ast.SwitchStmt) {
	if x.Tag == nil {
		return
	}
	if v.info != nil {
		v.checkEnumSwitchTyped(x)
		return
	}
	text := exprText(v.fset, v.file, x.Tag)
	if !strings.Contains(text, "Status") && !strings.Contains(text, "gen.") {
		return
	}
	var hasDefault bool
	cases := 0
	for _, cl := range x.Body.List {
		cc, ok := cl.(*ast.CaseClause)
		if !ok {
			continue
		}
		if cc.List == nil {
			hasDefault = true
		}
		cases++
	}
	if hasDefault {
		return
	}
	// Count the enum's declared values from the model when the tag names a field.
	field := strings.TrimSuffix(text[strings.LastIndex(text, ".")+1:], "()")
	total := 0
	for _, r := range v.cfg.App.AllResources() {
		for _, f := range r.Resource.Fields {
			if strings.EqualFold(f.GoName, field) && len(f.Type.Values) > total {
				total = len(f.Type.Values)
			}
		}
	}
	if total > 0 && cases < total {
		v.at("AM-CODE-003", x, fmt.Sprintf("the switch handles %d of %d enum values and has no default", cases, total),
			"list every value, or add a default that fails, so adding a value breaks the build")
	}
}

// checkEnumSwitchTyped counts distinct case values against the constants a generated
// enum type declares, whatever the tag expression is called.
func (v *visitor) checkEnumSwitchTyped(x *ast.SwitchStmt) {
	tn := named(v.info.TypeOf(x.Tag))
	if tn == nil || !isGenPkg(tn.Pkg()) {
		return
	}
	if b, ok := tn.Type().Underlying().(*types.Basic); !ok || b.Info()&types.IsString == 0 {
		return
	}
	all := map[string]bool{}
	scope := tn.Pkg().Scope()
	for _, name := range scope.Names() {
		if c, ok := scope.Lookup(name).(*types.Const); ok && types.Identical(c.Type(), tn.Type()) {
			all[c.Val().ExactString()] = true
		}
	}
	seen := map[string]bool{}
	for _, cl := range x.Body.List {
		cc, ok := cl.(*ast.CaseClause)
		if !ok {
			continue
		}
		if cc.List == nil {
			return // a default handles the rest
		}
		for _, e := range cc.List {
			if tv := v.info.Types[e]; tv.Value != nil {
				seen[tv.Value.ExactString()] = true
			}
		}
	}
	if len(all) > 0 && len(seen) < len(all) {
		v.at("AM-CODE-003", x, fmt.Sprintf("the switch handles %d of %d enum values and has no default", len(seen), len(all)),
			"list every value, or add a default that fails, so adding a value breaks the build")
	}
}

// sensitiveFieldTyped names the Sensitive field a selector reads, judged by the
// generated resource type it is read from rather than by the field's name alone.
func (v *visitor) sensitiveFieldTyped(sel *ast.SelectorExpr) string {
	s := v.info.Selections[sel]
	if s == nil || s.Kind() != types.FieldVal {
		return ""
	}
	tn := named(s.Recv())
	if tn == nil || !isGenPkg(tn.Pkg()) {
		return ""
	}
	for _, r := range v.cfg.App.AllResources() {
		if r.Resource.Name != tn.Name() {
			continue
		}
		for _, f := range r.Resource.Fields {
			if f.Sensitive && f.GoName == sel.Sel.Name {
				return r.Ref + "." + f.Name
			}
		}
	}
	return ""
}

// sensitiveField returns the field name when a selector reads a Sensitive field.
func (v *visitor) sensitiveField(sel *ast.SelectorExpr) string {
	name := sel.Sel.Name
	for _, r := range v.cfg.App.AllResources() {
		for _, f := range r.Resource.Fields {
			if f.Sensitive && f.GoName == name {
				return r.Ref + "." + f.Name
			}
		}
	}
	return ""
}

func (v *visitor) actionName(x ast.Node) string {
	if v.action != "" {
		return v.action
	}
	return strings.TrimSuffix(filepath.Base(v.path), ".go")
}

func (v *visitor) collectFacts() {
	for i, line := range v.lines {
		m := allowRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		v.res.Facts.Allows = append(v.res.Facts.Allows, model.AllowFact{
			Rule: m[1], File: v.path, Line: i + 1, Reason: strings.TrimSpace(m[2]),
		})
	}
}

func isDBCall(text string) bool {
	for _, m := range []string{".DB.", ".Query(", ".Get(", ".Insert(", ".Update(", ".Delete(", "Query().", ".Count("} {
		if strings.Contains(text, m) {
			return true
		}
	}
	return false
}

func isEffectCall(text string) bool {
	for _, m := range []string{".Email.", ".SMS.", ".HTTP.", ".Storage.", ".Webhook.", ".Enqueue("} {
		if strings.Contains(text, m) {
			return true
		}
	}
	return false
}

