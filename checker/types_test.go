// typedGen stands in for generated code: the real runtime types, so the typed rules
// resolve against what an app actually compiles with.
const typedGen = `// Code generated by am. DO NOT EDIT.

package gen

import (
	"context"
	"log/slog"

	"github.com/Grab-Connected-Tech/ambit/am"
	"github.com/Grab-Connected-Tech/ambit/runtime"
)

type InvoiceStatus string

const (
	InvoiceStatusDraft InvoiceStatus = "draft"
	InvoiceStatusSent  InvoiceStatus = "sent"
	InvoiceStatusPaid  InvoiceStatus = "paid"
	InvoiceStatusVoid  InvoiceStatus = "void"
)

type Invoice struct {
	ID     am.ID
	Notes  string
	Status InvoiceStatus
}

type InvoiceView = runtime.View[Invoice]

type SendInvoiceDB struct{ Invoices *InvoiceView }

type SendInvoiceCtx struct {
	context.Context
	Log   *slog.Logger
	DB    SendInvoiceDB
	Email runtime.EffectHandle
}
`

// The checker's tests, under types, of what syntax alone gets wrong in both
// directions: spellings that hide a call, and names that only look like one.
func TestTypedRulesSeeThroughSpelling(t *testing.T) {
	if testing.Short() {
		t.Skip("builds a module")
	}
	repo, _ := filepath.Abs("..")
	sum, err := os.ReadFile(filepath.Join(repo, "go.sum"))
	if err != nil {
		t.Fatal(err)
	}
	header := "package billing\n\nimport (\n\traw \"github.com/Grab-Connected-Tech/ambit/am\"\n\tclock \"time\"\n\n\t\"myapp/gen\"\n)\n\nvar _ = raw.ID(\"\")\nvar _ = clock.Second\nvar _ *gen.Invoice\n\n"
	root := tree(t, map[string]string{
		"go.mod": "module myapp\n\ngo 1.25.0\n\nrequire github.com/Grab-Connected-Tech/ambit v0.0.0\n\nreplace github.com/Grab-Connected-Tech/ambit => " + repo + "\n",
		"go.sum":     string(sum),
		"gen/gen.go": typedGen,
		// Evasions: each one is a real rule violation spelled so the text check misses it.
		"app/billing/unsafe.go": header + `func sendInvoice(c *gen.SendInvoiceCtx) error {
	return raw.Unsafe(c, "", func(tx raw.RawTx) error { return nil })
}

func unsafeValue() any { f := raw.Unsafe; return f }
`,
		"app/billing/clock.go": header + `func stamp() any { return clock.Now() }
`,
		"app/billing/enum.go": header + `func label(inv *gen.Invoice) string {
	s := inv.Status
	switch s {
	case gen.InvoiceStatusDraft:
		return "draft"
	}
	return ""
}
`,
		"app/billing/logs.go": header + `func logIt(c *gen.SendInvoiceCtx, inv *gen.Invoice) {
	c.Log.Info("invoice", "detail", "notes="+inv.Notes)
}

func sendIt(c *gen.SendInvoiceCtx) {
	c.Email.Send(c, nil)
}
`,
		// Look-alikes: each one trips the text check but is not a violation.
		"app/billing/lookalike.go": header + `type cache map[string]int

func (m cache) Get(k string) int { return m[k] }

type memo struct{ Notes string }

func fine(c *gen.SendInvoiceCtx, keys []string, m memo, inv *gen.Invoice) int {
	n := 0
	lookup := cache{}
	for _, k := range keys {
		n += lookup.Get(k)
	}
	c.Log.Info("memo", "notes", m.Notes)
	switch inv.Status {
	case gen.InvoiceStatusDraft, gen.InvoiceStatusSent, gen.InvoiceStatusPaid, gen.InvoiceStatusVoid:
	}
	return n
}
`,
	})
	t.Setenv("GOFLAGS", "-mod=mod")
	t.Setenv("GOPROXY", "off")
	res, err := Run(Config{Root: root, ModulePath: "myapp", App: testApp(), Types: true})
	if err != nil {
		t.Fatal(err)
	}
	lacks(t, res.Diags, "AM-CODE-006")
	in := func(rule, file string) int {
		n := 0
		for _, d := range res.Diags {
			if d.Rule == rule && d.File == file {
				n++
			}
		}
		return n
	}
	for _, c := range []struct {
		rule, file string
		want       int
	}{
		{"AM-SEC-003", "app/billing/unsafe.go", 2}, // aliased call with no reason; used as a value
		{"AM-CODE-004", "app/billing/clock.go", 1},
		{"AM-CODE-003", "app/billing/enum.go", 1},
		{"AM-SEC-004", "app/billing/logs.go", 1},
		{"AM-DATA-003", "app/billing/logs.go", 1},
		{"AM-DATA-002", "app/billing/lookalike.go", 0},
		{"AM-SEC-004", "app/billing/lookalike.go", 0},
		{"AM-CODE-003", "app/billing/lookalike.go", 0},
	} {
		if got := in(c.rule, c.file); got != c.want {
			t.Errorf("%s in %s: got %d, want %d\n%s", c.rule, c.file, got, c.want, show(res.Diags))
		}
	}
}

func TestFailedTypeCheckIsLoud(t *testing.T) {
	root := tree(t, map[string]string{"app/billing/x.go": "package billing\n"}) // no go.mod
	res, err := Run(Config{Root: root, ModulePath: "myapp", App: testApp(), Types: true})
	if err != nil {
		t.Fatal(err)
	}
	if d := has(t, res.Diags, "AM-CODE-006"); d.Severity != compile.SevError {
		t.Fatalf("a checker that silently checked less must fail the run: %s", d.Severity)
	}
}
