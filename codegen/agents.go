// AgentsMarkdown writes the instructions an agent reads before touching the app (§17.3).
// Regeneration replaces the generated part and keeps whatever a team wrote inside the
// marked section, so project knowledge survives a rebuild.
func AgentsMarkdown(app *model.App, preserved string) []byte {
	var b strings.Builder
	b.WriteString("# " + app.App.Name + " — agent instructions\n\n")
	b.WriteString("Generated by `am gen`. Everything outside the marked section below is replaced\n" +
		"when the spec changes; edit the spec, not this file.\n\n")
	b.WriteString("## The loop\n\n" +
		"1. `am gen` — compile the spec, regenerate `gen/`, migrations, clients and this file.\n" +
		"2. `am check` — build, vet and run the Ambit analyzers; fix every finding.\n" +
		"3. `am test` — generated policy tests plus yours, against a real Postgres.\n" +
		"4. `am migrate plan` — see what the schema change costs before applying it.\n" +
		"5. `am diff --base main` — the behaviour change a human reviews.\n\n")
	b.WriteString("## Modules\n\n")
	for _, m := range app.Modules {
		res := make([]string, len(m.Resources))
		for i, r := range m.Resources {
			res[i] = r.Name
		}
		acts := make([]string, 0, len(m.Actions))
		for _, a := range m.Actions {
			acts = append(acts, a.Name)
		}
		fmt.Fprintf(&b, "- **%s** — resources %s; actions %s\n", m.Name, orNone(res), orNone(acts))
	}
	b.WriteString("\n## Rules\n\n")
	b.WriteString("Access rules live in the spec, never in an action body. A query is scoped by the\n" +
		"tenant and the read rule before your code sees it, so a missing filter is not a leak.\n" +
		"The analyzers enforce the catalog below; `am explain <ID>` says why each exists.\n\n")
	b.WriteString("| Rule | Severity |\n| --- | --- |\n")
	for _, r := range checker.Catalog {
		fmt.Fprintf(&b, "| %s | %s |\n", r.ID, r.Severity)
	}
	b.WriteString("\n## Commands\n\n" +
		"| Command | What it does |\n| --- | --- |\n" +
		"| `am gen` | regenerate from the spec |\n" +
		"| `am check` | compiler, vet, analyzers, one diagnostic list |\n" +
		"| `am test` | generated and written tests against Postgres |\n" +
		"| `am migrate plan/apply/status` | schema work, classified |\n" +
		"| `am diff --base main` | behaviour diff for review |\n" +
		"| `am explain <RULE-ID>` | why a rule exists, with a fix |\n\n")
	b.WriteString("<!-- am:team-notes -->\n")
	if preserved != "" {
		b.WriteString(preserved + "\n")
	} else {
		b.WriteString("## Project notes\n\n" +
			"Add anything specific to this repository here. `am gen` preserves this section.\n")
	}
	b.WriteString("<!-- /am:team-notes -->\n")
	return []byte(b.String())
}

// teamNotes lifts the previous file's marked section out so regeneration can put it back.
func teamNotes(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return "", nil
		}
		return "", err
	}
	s := string(raw)
	i := strings.Index(s, "<!-- am:team-notes -->")
	j := strings.Index(s, "<!-- /am:team-notes -->")
	if i < 0 || j < 0 || j < i {
		return "", nil
	}
	return strings.TrimSpace(s[i+len("<!-- am:team-notes -->") : j]), nil
}

func orNone(items []string) string {
	if len(items) == 0 {
		return "none"
	}
	return strings.Join(items, ", ")
}
