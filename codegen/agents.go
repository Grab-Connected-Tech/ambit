// AgentsMarkdown writes the instructions an agent reads before touching the app (§17.3).
// Regeneration replaces the generated part and keeps whatever a team wrote inside the
// marked section, so project knowledge survives a rebuild.
func AgentsMarkdown(app *model.App, preserved string) []byte {
	var b strings.Builder
	b.WriteString("# " + app.App.Name + " — agent instructions\n\n")
	b.WriteString("Generated by `am gen`. Everything outside the marked section below is replaced\n" +
		"when the spec changes; edit the spec, not this file.\n\n")
	b.WriteString("## The loop\n\n" +
		"1. `am gen` — compile the spec, regenerate `gen/`, migrations, clients and this file.\n" +
		"2. `am check` — build, vet and run the Ambit analyzers; fix every finding.\n" +
		"3. `am test` — generated policy tests plus yours, against a real Postgres.\n" +
		"4. `am migrate plan` — see what the schema change costs before applying it.\n" +
		"5. `am diff --base main` — the behaviour change a human reviews.\n\n")
	b.WriteString("## Modules\n\n")
	for _, m := range app.Modules {
		res := make([]string, len(m.Resources))
		for i, r := range m.Resources {
			res[i] = r.Name
		}
		acts := make([]string, 0, len(m.Actions))
		for _, a := range m.Actions {
			acts = append(acts, a.Name)
		}
		fmt.Fprintf(&b, "- **%s** — resources %s; actions %s\n", m.Name, orNone(res), orNone(acts))
	}
	b.WriteString("\n## The pattern\n\n" +
		"Behaviour is declared in the module's `spec.go`; the action body only does the work.\n\n" +
		"```go\n" +
		"// spec.go — who may call it, what it touches, how it can fail\n" +
		"var SendInvoice = s.Mutation(\"SendInvoice\",\n" +
		"\ts.Input(s.ID(\"invoice_id\", Invoice)),\n" +
		"\ts.Returns(Invoice),\n" +
		"\ts.Requires(app.Admin.Or(app.Accountant)),\n" +
		"\ts.Writes(Invoice),\n" +
		"\ts.Effects(s.EmailEffect()),\n" +
		"\ts.Errors(\"not_draft\"),\n" +
		")\n\n" +
		"// actions.go — signature fixed by am gen; data via c.DB, time via c.Clock, effects via c\n" +
		"func sendInvoice(c *gen.SendInvoiceCtx, in gen.SendInvoiceInput) (*gen.Invoice, error) {\n" +
		"\tinv, err := c.DB.Invoices.Get(c, in.InvoiceID)\n" +
		"\tif err != nil {\n\t\treturn nil, err\n\t}\n" +
		"\tif inv.Status != gen.InvoiceStatusDraft {\n\t\treturn nil, gen.ErrSendInvoiceNotDraft()\n\t}\n" +
		"\tupdated, err := c.DB.Invoices.Update(c, inv.ID, inv.Version, gen.InvoicePatch{\n" +
		"\t\tStatus: am.Set(gen.InvoiceStatusSent),\n" +
		"\t\tSentAt: am.Set(c.Clock.Now()),\n" +
		"\t}.Assignments())\n" +
		"\tif err != nil {\n\t\treturn nil, err\n\t}\n" +
		"\tif _, err := c.Email.Send(c, []byte(\"{}\")); err != nil { // sent only if the transaction commits\n" +
		"\t\treturn nil, err\n\t}\n" +
		"\treturn updated, nil\n" +
		"}\n" +
		"```\n\n" +
		"`am check` refuses `database/sql`, `net/http`, `time.Now` and `go` statements in an\n" +
		"action. Role checks do not belong there either: access is declared in the spec, and so\n" +
		"are checks against the caller. \"Nobody approves their own expense\" is\n" +
		"`s.Update(app.Approver.And(s.Not(s.Owner(\"submitter\"))))`, not an `if` on `c.Actor.ID`.\n" +
		"A value rule such as a positive amount goes on the resource field (`.Min(1)`) or in\n" +
		"`s.Invariants`, so the database enforces it for every write, not only on one input.\n" +
		"`am context <module>` or `am context --action <module.Action>` prints the\n" +
		"spec and generated signatures for just the code you are changing.\n")
	b.WriteString("\n## Rules\n\n")
	b.WriteString("Access rules live in the spec, never in an action body. A query is scoped by the\n" +
		"tenant and the read rule before your code sees it, so a missing filter is not a leak.\n" +
		"`am check` fails on each of these; `am explain <ID>` shows a failing and a passing example.\n\n")
	b.WriteString("| Rule | Severity | Fails when |\n| --- | --- | --- |\n")
	for _, r := range checker.Catalog {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", r.ID, r.Severity, r.Title)
	}
	b.WriteString("\n## Commands\n\n" +
		"| Command | What it does |\n| --- | --- |\n" +
		"| `am gen` | regenerate from the spec |\n" +
		"| `am check` | compiler, vet, analyzers, one diagnostic list |\n" +
		"| `am test` | generated and written tests against Postgres |\n" +
		"| `am migrate plan/apply/status` | schema work, classified |\n" +
		"| `am diff --base main` | behaviour diff for review |\n" +
		"| `am explain <RULE-ID>` | why a rule exists, with a fix |\n" +
		"| `am actor create --field email=... --role ...` | an account and API token to call the app with; run it after `am dev` starts |\n\n")
	b.WriteString("<!-- am:team-notes -->\n")
	if preserved != "" {
		b.WriteString(preserved + "\n")
	} else {
		b.WriteString("## Project notes\n\n" +
			"Add anything specific to this repository here. `am gen` preserves this section.\n")
	}
	b.WriteString("<!-- /am:team-notes -->\n")
	return []byte(b.String())
}

// teamNotes lifts the previous file's marked section out so regeneration can put it back.
func teamNotes(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return "", nil
		}
		return "", err
	}
	s := string(raw)
	i := strings.Index(s, "<!-- am:team-notes -->")
	j := strings.Index(s, "<!-- /am:team-notes -->")
	if i < 0 || j < 0 || j < i {
		return "", nil
	}
	return strings.TrimSpace(s[i+len("<!-- am:team-notes -->") : j]), nil
}

func orNone(items []string) string {
	if len(items) == 0 {
		return "none"
	}
	return strings.Join(items, ", ")
}
