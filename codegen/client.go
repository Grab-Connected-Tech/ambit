package codegen

import (
	"fmt"
	"sort"
	"strings"

	"keystone.dev/keystone/ks"
	"keystone.dev/keystone/model"
)

// frameworkCodes are the error codes any action can return (§12.2).
var frameworkCodes = []string{
	ks.CodeInvalid, ks.CodeUnauthenticated, ks.CodeForbidden, ks.CodeNotFound, ks.CodeConflict,
	ks.CodeInvariant, ks.CodeRateLimited, ks.CodeBudget, ks.CodeTimeout, ks.CodeUnavailable,
	ks.CodeInternal, ks.CodeNotImplemented,
}

// TypeScriptClient emits the client of §12.3: createClient({ baseUrl }) returns one
// namespace per module, each action returns a discriminated Result instead of throwing,
// and the error type lists exactly the codes the action can produce. It has no runtime
// dependencies and uses fetch. Field names are the wire names the server encodes.
func TypeScriptClient(app *model.App) []byte {
	var b strings.Builder
	b.WriteString("// Generated by ks gen. Do not edit.\n\n")
	b.WriteString("export type FrameworkCode = " + tsUnion(frameworkCodes) + "\n\n")
	b.WriteString(tsPrelude)
	refs := app.AllResources()
	sort.Slice(refs, func(i, j int) bool { return refs[i].Ref < refs[j].Ref })
	for _, e := range refs {
		b.WriteString("export interface " + tsName(e.Ref) + " {\n")
		for _, f := range e.Resource.Fields {
			opt := ""
			if f.Optional {
				opt = "?"
			}
			b.WriteString("  " + tsKey(wireName(&f)) + opt + ": " + tsType(&f) + "\n")
		}
		b.WriteString("}\n\n")
	}
	mods := append([]model.Module(nil), app.Modules...)
	sort.Slice(mods, func(i, j int) bool { return mods[i].Name < mods[j].Name })
	b.WriteString("export function createClient(options: ClientOptions = {}) {\n")
	b.WriteString("  const call = makeCaller(options)\n  return {\n")
	for _, m := range mods {
		acts := append([]model.Action(nil), m.Actions...)
		sort.Slice(acts, func(i, j int) bool { return acts[i].Name < acts[j].Name })
		var lines []string
		for _, a := range acts {
			if a.Kind == model.KindJob || a.Kind == model.KindSchedule {
				continue
			}
			codes := make([]string, 0, len(a.Errors))
			for _, e := range a.Errors {
				codes = append(codes, e.Code)
			}
			errType := "never"
			if len(codes) > 0 {
				errType = tsUnion(codes)
			}
			fields := tsFields(a.Input)
			if a.Output.Page != "" {
				// Paged queries take the keyset cursor and a page size (§8.1).
				fields = strings.TrimPrefix(fields+"; cursor?: string; limit?: number", "; ")
			}
			input, optional := "Record<string, never>", true
			if fields != "" {
				input = "{ " + fields + " }"
			}
			for _, f := range a.Input {
				optional = optional && f.Optional
			}
			doc := ""
			if a.Deprecated != "" {
				doc = "      /** @deprecated " + strings.ReplaceAll(a.Deprecated, "*/", "* /") + " */\n"
			}
			lines = append(lines, fmt.Sprintf("%s      %s: (input: %s%s, opts?: CallOptions) =>\n        call<%s, %s>(%q, input, %t, %t, opts),\n",
				doc, lowerFirst(a.Name), input, map[bool]string{true: " = {}", false: ""}[optional],
				tsOutput(&a), errType, "/"+m.Name+"/"+a.Name, a.AllowGet, a.Idempotent))
		}
		if len(lines) == 0 {
			continue
		}
		b.WriteString("    " + tsKey(m.Name) + ": {\n" + strings.Join(lines, "") + "    },\n")
	}
	b.WriteString("  }\n}\n")
	return []byte(b.String())
}

// tsName turns "customers.Customer" into "CustomersCustomer", the identifier shape a
// TypeScript interface needs.
func tsName(ref string) string {
	m, n := splitRef(ref)
	if m == "" || m == "app" {
		return n
	}
	return title(m) + n
}

func tsOutput(a *model.Action) string {
	switch {
	case a.Output.Resource != "":
		return tsName(a.Output.Resource)
	case a.Output.Page != "":
		return "Page<" + tsName(a.Output.Page) + ">"
	case len(a.Output.Fields) > 0:
		return "{ " + tsFields(a.Output.Fields) + " }"
	default:
		return "void"
	}
}

func tsFields(fields []model.Field) string {
	var parts []string
	for _, f := range fields {
		opt := ""
		if f.Optional {
			opt = "?"
		}
		parts = append(parts, tsKey(f.Name)+opt+": "+tsType(&f))
	}
	return strings.Join(parts, "; ")
}

func tsType(f *model.Field) string {
	switch f.Type.Kind {
	case model.KindInt:
		return "number"
	case model.KindMoney:
		return "Money"
	case model.KindBool:
		return "boolean"
	case model.KindJSON:
		return "Record<string, unknown>"
	case model.KindEnum:
		return tsUnion(f.Type.Values)
	default:
		return "string"
	}
}

func tsUnion(vals []string) string {
	parts := make([]string, len(vals))
	for i, v := range vals {
		parts[i] = fmt.Sprintf("%q", v)
	}
	return strings.Join(parts, " | ")
}

// tsKey quotes a property name unless it is a plain identifier.
func tsKey(k string) string {
	for i, r := range k {
		if !(r == '_' || r == '$' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9') {
			return fmt.Sprintf("%q", k)
		}
	}
	return k
}

const tsPrelude = `export interface KsError<C extends string> {
  code: C | FrameworkCode
  message: string
  fields?: Record<string, string>
  traceId?: string
  status: number
}

export type Result<T, C extends string = never> =
  | { ok: true; value: T }
  | { ok: false; error: KsError<C> }

export interface Money { minor: number; currency: string }

export interface Page<T> { rows: T[]; nextCursor?: string }

export interface ClientOptions {
  baseUrl?: string
  headers?: Record<string, string>
  fetch?: typeof fetch
}

export interface CallOptions { idempotencyKey?: string; signal?: AbortSignal }

function makeCaller(options: ClientOptions) {
  const base = (options.baseUrl ?? "/api").replace(/\/$/, "")
  const doFetch = options.fetch ?? fetch
  return async function call<T, C extends string>(
    path: string, input: unknown, get: boolean, idempotent: boolean, opts?: CallOptions,
  ): Promise<Result<T, C>> {
    const headers: Record<string, string> = { ...(options.headers ?? {}) }
    let url = base + path
    const init: RequestInit = { credentials: "include", headers, signal: opts?.signal }
    if (get) {
      const q = new URLSearchParams()
      for (const [k, v] of Object.entries((input ?? {}) as Record<string, unknown>)) {
        if (v !== undefined && v !== null) q.set(k, typeof v === "object" ? JSON.stringify(v) : String(v))
      }
      const qs = q.toString()
      if (qs) url += "?" + qs
      init.method = "GET"
    } else {
      init.method = "POST"
      headers["content-type"] = "application/json"
      init.body = JSON.stringify(input ?? {})
      if (idempotent) headers["idempotency-key"] = opts?.idempotencyKey ?? crypto.randomUUID()
    }
    let res: Response
    try {
      res = await doFetch(url, init)
    } catch (e) {
      return { ok: false, error: { code: "unavailable", message: String(e), status: 0 } }
    }
    if (res.status === 204) return { ok: true, value: undefined as T }
    const body: any = await res.json().catch(() => ({}))
    if (!res.ok) {
      const e = body?.error ?? {}
      return { ok: false, error: { code: e.code ?? "internal", message: e.message ?? res.statusText, fields: e.fields, traceId: e.traceId, status: res.status } }
    }
    return { ok: true, value: body as T }
  }
}

`
