package codegen

import (
	"fmt"
	"strings"

	"keystone.dev/keystone/model"
)

// TypeScriptClient emits a typed client for the same model the server was generated from,
// so a frontend cannot call an action that does not exist (§7.1). It is deliberately small:
// one function per action, interfaces for the resources, and a single request helper.
func TypeScriptClient(app *model.App) []byte {
	var b strings.Builder
	b.WriteString("// Generated by ks gen. Do not edit.\n\n")
	b.WriteString(tsError)
	b.WriteString(tsRequest)
	for _, e := range app.AllResources() {
		res := e.Resource
		b.WriteString("export interface " + tsName(e.Ref) + " {\n")
		for _, f := range res.Fields {
			opt := ""
			if f.Optional {
				opt = "?"
			}
			b.WriteString("  " + camel(f.Name) + opt + ": " + tsType(&f) + "\n")
		}
		b.WriteString("}\n\n")
	}
	for m := range app.Modules {
		for i := range app.Modules[m].Actions {
			a := &app.Modules[m].Actions[i]
			if a.Kind == model.KindJob || a.Kind == model.KindSchedule {
				continue
			}
			ref := fmt.Sprintf("/api/%s/%s", app.Modules[m].Name, a.Name)
			b.WriteString("export function " + a.Name + "(")
			if len(a.Input) > 0 {
				b.WriteString("input: { " + tsFields(a.Input) + " }")
			} else {
				b.WriteString("input?: Record<string, never>")
			}
			b.WriteString("): Promise<" + tsOutput(a) + "> {\n")
			if a.Kind == model.KindQuery {
				b.WriteString("  const q = new URLSearchParams((input ?? {}) as any).toString()\n")
				b.WriteString("  return request<" + tsOutput(a) + ">(`" + ref + "?${q}`)\n}\n\n")
				continue
			}
			b.WriteString("  return request<" + tsOutput(a) + ">(\"" + ref + "\", {\n")
			b.WriteString("    method: \"POST\", headers: { \"content-type\": \"application/json\" },\n")
			b.WriteString("    body: JSON.stringify(input),\n  })\n}\n\n")
		}
	}
	return []byte(b.String())
}

// tsName turns "customers.Customer" into "customers.Customer" with the dot removed, which
// is the identifier shape a TypeScript interface needs.
func tsName(ref string) string {
	m, n := splitRef(ref)
	if m == "" {
		return n
	}
	return title(m) + n
}

func tsOutput(a *model.Action) string {
	switch {
	case a.Output.Resource != "":
		return tsName(a.Output.Resource)
	case a.Output.Page != "":
		return "{ rows: " + tsName(a.Output.Page) + "[]; nextCursor?: string }"
	case len(a.Output.Fields) > 0:
		return "{ " + tsFields(a.Output.Fields) + " }"
	default:
		return "void"
	}
}

func tsFields(fields []model.Field) string {
	var parts []string
	for _, f := range fields {
		opt := ""
		if f.Optional {
			opt = "?"
		}
		parts = append(parts, camel(f.Name)+opt+": "+tsType(&f))
	}
	return strings.Join(parts, "; ")
}

func tsType(f *model.Field) string {
	switch f.Type.Kind {
	case model.KindInt, model.KindDecimal:
		if f.Type.Kind == model.KindDecimal {
			return "string"
		}
		return "number"
	case model.KindBool:
		return "boolean"
	case model.KindJSON:
		return "Record<string, unknown>"
	case model.KindEnum:
		parts := make([]string, len(f.Type.Values))
		for i, v := range f.Type.Values {
			parts[i] = "\"" + v + "\""
		}
		return strings.Join(parts, " | ")
	default:
		return "string"
	}
}

func camel(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' })
	if len(parts) == 0 {
		return s
	}
	out := strings.ToLower(parts[0])
	for _, p := range parts[1:] {
		out += title(p)
	}
	return out
}

const tsError = "export class KeystoneError extends Error {\n  code: string\n  status: number\n" +
	"  constructor(code: string, message: string, status: number) {\n    super(message)\n" +
	"    this.code = code\n    this.status = status\n  }\n}\n\n"

const tsRequest = "async function request<T>(path: string, init?: RequestInit): Promise<T> {\n" +
	"  const res = await fetch(path, { credentials: \"include\", ...init })\n" +
	"  const body: any = await res.json().catch(() => ({}))\n" +
	"  if (!res.ok) {\n    const e = body?.error ?? {}\n" +
	"    throw new KeystoneError(e.code ?? \"internal\", e.message ?? res.statusText, res.status)\n  }\n" +
	"  return body as T\n}\n\n"
